-- 021_metric_schedule.sql
--
-- "Рваные" ежедневные метрики: расписание, чтобы стрик не рвался в дни, когда метрику
-- делать не нужно. Одно необязательное поле jsonb на метрику:
--   null                                   — каждый день (как было раньше, для всех существующих метрик)
--   {"type": "days",   "days": [1, 3, 5]}  — только в эти дни недели (0 = воскресенье ... 6 = суббота)
--   {"type": "weekly", "min": 5}           — не менее N раз в неделю (неделя пн-вс), в любые дни
-- Стрик для "days" не рвётся в нерасчётные дни, для "weekly" считается в неделях.
-- Таблица daily_values и лидерборд не меняются (серия в лидерборде считается как раньше).

alter table metrics add column if not exists schedule jsonb;
