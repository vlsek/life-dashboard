-- «Прогрессивные программы»: активная программа тренировок (BACKLOG 3.3, остаток: «Начать программу», подсказка текущей недели, отметка
-- пройденных недель; агент 7). ПРИМЕНИТЬ В SUPABASE SQL EDITOR (одним запуском; повторный запуск безопасен).
--
-- Формат — jsonb-объект: {"templateId": "pushups_6w", "startDate": "2026-10-03", "doneWeeks": [0, 1]}
--   templateId — id программы из типовых программ (Workouts → «Типовые программы»);
--   startDate  — день старта «ГГГГ-ММ-ДД» (по нему считается текущая неделя: дни 0–6 — неделя 1 и т. д.);
--   doneWeeks  — номера пройденных недель с нуля (0 = «Неделя 1»).
-- null = активной программы нет. Права и RLS не меняются: профиль пользователь читает и правит сам, как и favorite_pages (035).
--
-- Без этой миграции программа работает, но только на этом устройстве (localStorage `workout_program`) и не синхронизируется.

alter table profiles add column if not exists workout_program jsonb;
