-- 054_metric_source_exercise.sql
-- Метрики дня: связь с упражнением из «Тренировок» (BACKLOG 19 «13:06 — это упражнение?», 30 «аналогичный прогресс в Тренировках»,
-- «8:29 — третий раз»; РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-10-06: делаем со связью, подходы вводятся ОДИН раз, тренировка и метрика считаются вместе
-- и не дублируют друг друга).
-- ПРИМЕНЯТЬ В SUPABASE SQL EDITOR (одним запуском; повторный запуск безопасен).
--
-- Как работает (так же, как у челленджей, миграция 042): «Тренировки» — единственный источник правды по подходам. Клиент раздела
-- «Тренировки» после каждого добавления/правки/удаления записи пересчитывает значение связанной метрики за эту дату и пишет его в
-- daily_values (для типа «Подходы» — список подходов [{reps, variation, time}], для «Число» — сумма повторов). Серверные функции баллов,
-- рейтинга и серий (calc_user_points, get_leaderboard, …) по-прежнему читают daily_values и НИЧЕГО не знают про эту колонку — менять их не нужно.
-- На Дашборде связанная метрика показывается только для чтения («ведётся в Тренировках»), чтобы подходы не вводились дважды.
--
-- Только добавляющая миграция. Если упражнение удалят, ссылка обнуляется (on delete set null): метрика и её значения за прошлые дни остаются,
-- метрика снова редактируется на Дашборде вручную. Права: колонка в metrics — действует прежняя RLS-политика владельца, новых политик не нужно.
-- Без миграции всё работает как раньше: раздел «Тренировки» сам видит, что колонки нет, и не показывает кнопку «В метрики дня».

alter table metrics add column if not exists source_exercise_id uuid references workout_exercises(id) on delete set null;

-- Одна метрика — одно упражнение, но упражнение может питать несколько метрик (например, «Отжимания» и «Отжимания утром»).
create index if not exists metrics_source_exercise_idx on metrics(source_exercise_id) where source_exercise_id is not null;

comment on column metrics.source_exercise_id is
  'Упражнение из «Тренировок», из подходов которого клиент считает значение метрики за день (миграция 054). NULL — метрика ведётся вручную на Дашборде.';
