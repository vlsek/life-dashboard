-- 055_water_tracking_flag.sql
-- Флаг «Отслеживать воду» в профиле (BACKLOG 932 «Вода: дать возможность отключить учёт воды совсем»; ответ владельца 2026-10-07: флаг в профиле, миграция 055;
-- после выключения прошлые баллы за воду ОСТАЮТСЯ в балансе и достижениях).
-- ПРИМЕНИТЬ В SUPABASE SQL EDITOR (одним запуском; повторный запуск безопасен).
--
-- true (по умолчанию, у всех существующих профилей) — вода работает как раньше. false — клиент прячет стакан, окно воды, напоминания и блок «Вода» на
-- Дашборде и не учитывает воду в кольцах дня/недели, «идеальных днях», сериях и «баллах за день». Данные воды и баланс НЕ трогаются: записи в daily_values/water_log
-- остаются, баллы за прошлую воду считаются как раньше (баланс читает все активные метрики). Серверные функции баллов (033/043…) не менялись.
-- Читает и пишет сам пользователь через существующие политики RLS профиля (как favorite_pages / dashboard_charts) — отдельных политик не нужно.
-- Без этой миграции клиент работает как раньше (флага нет → вода включена), выключатель в настройках покажет понятную ошибку при сохранении.
-- Откат: alter table profiles drop column if exists track_water;

alter table profiles add column if not exists track_water boolean not null default true;

comment on column profiles.track_water is 'Отслеживать воду: false — клиент не показывает воду и не считает её в кольцах/сериях (данные и баллы за прошлое остаются). BACKLOG 932, миграция 055.';
