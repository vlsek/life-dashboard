-- 017_metric_input_mode.sql
--
-- Режим ввода для числовых метрик: 'set' (по умолчанию, как раньше — вписываешь
-- итоговое значение целиком) или 'add' (вписываешь дельту, она прибавляется к уже
-- сохранённому значению за этот день, поле после добавления очищается). Полезно для
-- метрик вида "Отжимания", когда за день делаешь несколько подходов в разное время —
-- не нужно помнить и перепечатывать текущую сумму каждый раз.

alter table metrics add column if not exists input_mode text default 'set';
