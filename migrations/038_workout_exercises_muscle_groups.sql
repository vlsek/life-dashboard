-- 038_workout_exercises_muscle_groups.sql
-- Группы мышц упражнения, которые человек сам отметил в форме упражнения (Workouts, BACKLOG 22 «12:33 — упражнение:
-- дополнительно отметить группы мышц из списка для схемы»; синхронизация между устройствами — v2.32 хранила их только
-- в localStorage устройства).
-- ПРИМЕНИТЬ В SUPABASE SQL EDITOR (одним запуском; повторный запуск безопасен).
--
-- Что хранится: массив id групп мышц ('chest', 'back', 'shoulders', 'biceps', 'triceps', 'forearms', 'abs', 'glutes',
-- 'quads', 'hamstrings', 'calves', 'lower_back' — те же, что на карте мышц в приложении). NULL — «своей привязки нет»:
-- работает автоматическое распознавание по названию упражнения. Непустой массив перекрывает автоматическое.
--
-- Права: колонка в таблице workout_exercises, поэтому действует прежняя RLS-политика «own workout_exercises»
-- (читать/писать только свои строки) — отдельных политик не нужно.
--
-- Без этой миграции всё продолжает работать как в v2.32: приложение само определяет, что колонки ещё нет, не пишет в неё
-- и хранит привязку только в localStorage устройства. После применения: при первой загрузке упражнений каждое устройство
-- ОДИН раз загружает в БД свои локальные привязки (там, где в БД пусто), дальше источник правды — БД.

alter table workout_exercises add column if not exists muscle_groups text[];

comment on column workout_exercises.muscle_groups is
  'Группы мышц, отмеченные пользователем (id как на карте мышц). NULL — своей привязки нет, работает автораспознавание по названию.';
