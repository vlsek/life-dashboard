-- 042_challenges_source_exercise.sql
-- Челленджи: источник значений — упражнение из Workouts (BACKLOG 14, «11:28 — Челленджи: значение из тренировок»;
-- решение владельца 2026-10-03: привязка к конкретному упражнению, значение дня = сумма повторов по всем подходам,
-- дни до даты старта не правим).
-- ПРИМЕНЯТЬ В SUPABASE SQL EDITOR (одним запуском; повторный запуск безопасен).
--
-- Как работает: пока за день нет ручной записи в challenge_entries, значение дня считается из workout_entries выбранного
-- упражнения (сумма reps по всем подходам всех записей за этот день). Ручная запись за день всегда главнее. Расчёт делает
-- клиент (web-challenges), в challenge_entries ничего не копируется — тренировки остаются единственным источником правды.
-- У челленджа может быть ОДИН источник: метрика (032) или упражнение (эта миграция); клиент сбрасывает второй при смене.
--
-- Только добавляющая миграция. Если упражнение удалят, ссылка обнуляется (on delete set null), челлендж и его ручные
-- записи остаются. Права: колонка в challenge_instances — действует прежняя RLS-политика, новых политик не нужно.
-- Без миграции раздел работает как раньше: приложение само видит, что колонки нет, и скрывает выбор упражнения в форме.

alter table challenge_instances add column if not exists source_exercise_id uuid references workout_exercises(id) on delete set null;
