-- 041_metric_planned_sets.sql
-- «Сколько подходов планируется в день» для метрик-подходов (BACKLOG 4.2 «Не меньше X подходов» + раздел 13 «Баллы за подход»,
-- решение владельца 2026-10-03). Первый срез — только хранение и правило «выполнено» в пилоте Дашборда.
-- ПРИМЕНЯТЬ В SUPABASE SQL EDITOR (одним запуском; повторный запуск безопасен). Рекомендуется применять вместе со следующими
-- срезами (остальные пилоты и SQL серий/баллов) — пока они не сделаны, поле в форме метрики лучше не заполнять.
--
-- Что хранится: ЖУРНАЛ изменений по возрастанию дат — jsonb-массив [{"from": "2026-10-01", "n": 3}, {"from": "2026-10-10", "n": 4}].
-- «n» — плановое число подходов в день с даты «from» (null — параметр снят с этой даты). Журнал, а не одно число, потому что
-- прошлые дни НЕ пересчитываются (баланс и магазин не должны «прыгать»): каждый день считается по правилу, действовавшему в
-- этот день. До первой записи журнала действует прежнее правило (сумма повторов >= goal_value). NULL — параметр не задавали.
-- Правило с N: метрика выполнена, когда сделано не меньше N подходов И (если задан) достигнут общий объём goal_value.
--
-- Права: колонка в таблице metrics — действует прежняя RLS-политика (читать/писать только свои метрики), новых политик не нужно.
-- Без миграции всё работает как раньше: приложение само видит, что колонки нет, и скрывает поле в форме метрики.

alter table metrics add column if not exists planned_sets_log jsonb;

comment on column metrics.planned_sets_log is
  'История планового числа подходов в день: [{"from":"YYYY-MM-DD","n":int|null}, ...] по возрастанию дат; null = не задано (старое правило)';
