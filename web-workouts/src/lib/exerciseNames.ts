// Единый регистр названий упражнений (BACKLOG 54.4, владелец 2026-10-10: «часть типовых упражнений с маленькой буквы, часть с большой»):
// название начинается с заглавной буквы. Меняется только первая буква-строчная; цифры, символы и уже заглавные не трогаем,
// остальной текст (в том числе «ё», дефисы, регистр внутри) — как написал человек.
export function capFirst(name: string): string {
  const s = name.trim()
  if (!s) return s
  const c = s.charAt(0)
  return c !== c.toUpperCase() ? c.toUpperCase() + s.slice(1) : s
}
