// «Тема применена на странице» (баг владельца 2026-10-11: после смены темы в «Кастомизации» в выборе тем бокового меню оставалась
// старая запись). Тему на этой странице меняет не само меню, а карточки тем (useFavoriteThemes.apply) — меню о смене не знало, держало
// прежнее значение и прежнюю активную тему в списке. Теперь apply() сообщает о смене, а меню перечитывает активную тему.
// Только внутри «Кастомизации» (lib/theme.ts одинаков во всех пилотах и охраняется — его не трогаем).
export const THEME_APPLIED_EVENT = 'site-theme:applied'

export function notifyThemeApplied(): void {
  window.dispatchEvent(new CustomEvent(THEME_APPLIED_EVENT))
}
