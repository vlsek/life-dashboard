function getLang() {
    return localStorage.getItem("site_lang") || "en";
}

function setLang(lang) {
    localStorage.setItem("site_lang", lang);
    // Не только applyI18n() для статичной разметки: большая часть контента на
    // страницах дашборда генерируется JS-ом (таблицы, алерты) и не переиспользует
    // data-i18n. Простой и надёжный способ переключить язык везде — перезагрузить
    // страницу, тогда весь JS-рендер пройдёт заново уже с новым языком.
    location.reload();
}

function t(key) {
    const lang = getLang();
    return (translations[lang] && translations[lang][key]) ?? translations.en[key] ?? key;
}

function applyI18n() {
    const lang = getLang();
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
        el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll(".lang-btn").forEach(btn => {
        btn.classList.toggle("active", btn.dataset.lang === lang);
    });
}

function renderLangSwitcher(parent) {
    const wrap = document.createElement("div");
    wrap.className = "lang-switch";
    ["en", "ru"].forEach(l => {
        const btn = document.createElement("button");
        btn.className = "lang-btn" + (getLang() === l ? " active" : "");
        btn.textContent = l.toUpperCase();
        btn.dataset.lang = l;
        btn.onclick = () => setLang(l);
        wrap.appendChild(btn);
    });
    parent.appendChild(wrap);
    return wrap;
}

document.addEventListener("DOMContentLoaded", applyI18n);
