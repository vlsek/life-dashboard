export type DictKey = keyof (typeof DICT)['ru']

export function getLang(): 'en' | 'ru' {
  try {
    return (localStorage.getItem('site_lang') || 'en') === 'ru' ? 'ru' : 'en'
  } catch {
    return 'en'
  }
}

export function t(key: DictKey): string {
  return DICT[getLang()][key]
}
